missingWords.forEach(word => {
  let tip = "";
  for (let i = 0; i < word.length; i++) {
    const char = word[i];
    if (charMeanings[char]) {
      tip += `'${char}'(${charMeanings[char]}) `;
    }
  }
  if (tip) {
    tips[word] = `한자 뜻풀이: ${tip.trim()}의 의미가 결합되어 만들어진 단어입니다.`;
  } else {
    tips[word] = `'${word}'의 발음과 뜻을 소리내어 여러 번 읽어보세요.`;
  }
});

let output = `export const tips: Record<string, string> = {\n`;
for (const [word, tip] of Object.entries(tips)) {
  output += `  '${word}': ${JSON.stringify(tip)},\n`;
}
output += `};\n`;

fs.writeFileSync('./data/tips.ts', output);
console.log('Generated tips.ts with ' + Object.keys(tips).length + ' entries.');
