type ToeicPart5QuestionDraft = Omit<ToeicPart5QuestionSource, 'id' | 'difficulty' | 'internalLevel'> & {
  internalLevel?: number;
};

function buildPart5Questions(
  prefix: 'p5-b' | 'p5-i' | 'p5-a',
  difficulty: ToeicPart5Difficulty,
  defaultInternalLevel: number,
  questions: ToeicPart5QuestionDraft[],
): ToeicPart5QuestionSource[] {
  return questions.map((question, index) => ({
    ...question,
    id: `${prefix}-${String(index + 7).padStart(3, '0')}`,
    difficulty,
    internalLevel: question.internalLevel ?? defaultInternalLevel,
  }));
}

