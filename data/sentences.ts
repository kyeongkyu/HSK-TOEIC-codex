// Helper to split Chinese sentences (improved dictionary-based segmentation)
function splitChinese(sentence: string | undefined, targetWord: string): string[] {
  if (!sentence) return [];
  
  // Clean sentence from basic punctuation for tokenization
  let text = sentence.replace(/[。！？，、]/g, '');
  
  const dictionary = new Set<string>();
  if (targetWord) dictionary.add(targetWord);
  
  // Add all HSK words to the dictionary
  hskWords.forEach(w => {
    if (w.word) dictionary.add(w.word);
  });
  
  // Add common particles, pronouns, and numbers
  const extraWords = [
    '我', '你', '他', '她', '它', '我们', '你们', '他们', '她们', '它们',
    '的', '了', '吗', '呢', '吧', '是', '在', '有', '个', '不', '很', '都', '也', '还', '就', '才',
    '这', '那', '哪', '什么', '谁', '怎么', '多少', '几', '太', '岁',
    '和', '做', '看', '听', '说', '读', '写', '想', '喜欢', '认识',
    '一', '二', '三', '四', '五', '六', '七', '八', '九', '十', '百', '千', '万',
    '北京', '老师', '学生', '医生', '朋友', '先生', '小姐', '衣服',
    '水', '茶', '米饭', '水果', '苹果', '杯子', '钱', '飞机', '出租车',
    '电视', '电脑', '电影', '天气', '猫', '狗', '东西', '人', '名字',
    '书', '字', '桌子', '椅子', '点', '分钟', '现在', '今天', '明天',
    '昨天', '上午', '中午', '下午', '年', '月', '日', '星期', '时候',
    '里', '前面', '后面', '左边', '右边', '上面', '下面',
    '家', '学校', '饭店', '商店', '医院', '车站', '中国'
  ];
  extraWords.forEach(w => dictionary.add(w));

  const tokens: string[] = [];
  let i = 0;
  while (i < text.length) {
    let matched = false;
    
    // 1. Priority: Try to match the targetWord exactly at this position
    if (targetWord && text.startsWith(targetWord, i)) {
      tokens.push(targetWord);
      i += targetWord.length;
      matched = true;
      continue;
    }

    // 2. Maximum Forward Matching: Try matching longest words in dictionary (up to 6 chars)
    for (let len = 6; len >= 1; len--) {
      const sub = text.substring(i, i + len);
      if (dictionary.has(sub)) {
        tokens.push(sub);
        i += len;
        matched = true;
        break;
      }
    }
    
    if (!matched) {
      // 3. Fallback: Take 1 character
      tokens.push(text[i]);
      i++;
    }
  }
  
  return tokens;
}

// Helper to split Korean sentences
function splitKorean(sentence: string | undefined): string[] {
  if (!sentence) return [];
  return sentence.split(' ').filter(t => t.length > 0);
}

